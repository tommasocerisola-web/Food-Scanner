_CURATED_UPPER: dict[str, tuple[int, str]] = {key.upper(): value for key, value in CURATED.items()}


def curated(e_number: str) -> tuple[int, str] | None:
    return _CURATED_UPPER.get(e_number.upper())


def why_for_class(classes: tuple[str, ...] | list[str]) -> str:
    for cls in classes:
        if cls in CLASS_WHY:
            return CLASS_WHY[cls]
    return DEFAULT_WHY
